def pick[T](rng: random.Random, items: list[T]) -> T:
    return items[rng.randrange(len(items))]


def compose(rng: random.Random, to_name: str, from_name: str, lines: list[str]) -> str:
    """인사 + 문장들 + 맺음말. 결정적이다(rng가 같으면 같은 결과)."""
    head = pick(rng, _GREET).format(to=to_name)
    tail = pick(rng, _CLOSE).format(frm=from_name)
    return f"{head}\n" + " ".join(lines) + f"\n{tail}"


def compose_auto(rng: random.Random, genre: str, topic: str) -> list[str]:
    """notice·newsletter·spam 본문용 문장들(수신자 이름 없음)."""
    pool = {"notice": NOTICE_LINES, "newsletter": NEWSLETTER_LINES, "spam": SPAM_LINES}[genre]
    first = pick(rng, pool)
    second = pick(rng, [x for x in pool if x != first])
    return [first, second] if genre != "spam" else [first]


def business_lines(rng: random.Random, topic: str, n: int = 2) -> list[str]:
    pool = list(GENERIC_BUSINESS)
    rng.shuffle(pool)
    return [x.format(topic=topic) for x in pool[:n]]


def doc_text(title: str, lines: list[str]) -> str:
    return f"{title}\n" + "\n".join(f"- {x}" for x in lines)
