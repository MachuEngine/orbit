def test_모든_사실이_충족돼야_한다() -> None:
    facts = [["11월 24일", "11/24"], ["3통"]]
    assert facts_pass(facts, "11/24에 세 통")
    assert not facts_pass(facts, "11/24에 네 통")


def test_빈_후보는_일치가_아니다() -> None:
    assert not facts_pass([[""]], "아무 말")
    assert not facts_pass([["..."]], "아무 말")


def test_사원_같은_낱말을_금액으로_읽지_않는다() -> None:
    assert normalize_answer("신입사원 오리엔테이션") == "신입사원 오리엔테이션"
    assert normalize_answer("사원 5명") != normalize_answer("사원 6명")
    assert "\ue000w" in normalize_answer("십만 원")
    assert "\ue000w" not in normalize_answer("사원")
    assert hit("신입사원", "신입사원 3명")


def test_버전_상수() -> None:
    assert RAG_ANSWER_NORM_VERSION == "rag-answer-norm-v3"


def gold_view(any_of: list[str]) -> GoldView:
    return GoldView.model_validate(
        {"answer_facts": [{"fact_id": "f", "description": "d", "any_of": any_of}]}
    )


def test_채점_기본은_기존_규칙이다() -> None:
    gold = gold_view(["3통"])
    assert not check_answer_facts(gold, "세 통")  # 기존 데이터셋 채점은 바뀌지 않는다
    assert check_answer_facts(gold, "세 통", rag_norm=True)
    assert check_answer_facts(gold, "3통")
    assert text_fact_recall(gold, "세 통") == 0.0
    assert text_fact_recall(gold, "세 통", rag_norm=True) == 1.0
